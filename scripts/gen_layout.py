"""Generate evision_rgb/layout.py by joining the official app's virtual keyboard (key names + pixel
positions, keyboarddevice.xml) with the device keymap read by cmd 0x07 (slot -> HID usage)."""
import os, re, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
xml = open(os.path.join(ROOT, "work/bin/XML/DeviceXml/keyboarddevice.xml"), encoding="utf-8").read()
keymap = open(sys.argv[1], "rb").read()  # backup/<ts>/keymap.bin

keys = re.findall(r'<DeviceKeyButton name="key_(\d+)"[^>]*?pos="(\d+),(\d+),[^"]*" width="(\d+)" height="(\d+)"'
                  r'[^>]*?tooltip="([^"]*)"[^>]*?visible="true"', xml, re.S)

letters = {c: 0x04 + i for i, c in enumerate("ABCDEFGHIJKLMNOPQRSTUVWXYZ")}
usage = {**letters, **{str((i + 1) % 10): 0x1E + i for i in range(10)},
         **{f"F{i}": 0x39 + i for i in range(1, 13)},
         "Esc": 0x29, "`": 0x35, "-": 0x2D, "+": 0x2E, "BackSpace": 0x2A, "Tab": 0x2B, "[": 0x2F,
         "]": 0x30, "\\\\": 0x31, "CapsLock": 0x39, ";": 0x33, "'": 0x34, "Enter": 0x28, ",": 0x36,
         ".": 0x37, "/": 0x38, "Space": 0x2C, "Delete": 0x4C, "Home": 0x4A, "PageUp": 0x4B,
         "PageDown": 0x4E, "End": 0x4D, "Up": 0x52, "Down": 0x51, "Left": 0x50, "Right": 0x4F}
modbit = {"Ctrl": 0x01, "Shift": 0x02, "Alt": 0x04, "Win": 0x08, "Right Ctrl": 0x10,
          "Rightshift": 0x20, "Right Alt": 0x40}
canon = {"\\\\": "Backslash", "+": "Equal", "-": "Minus", "`": "Grave", "[": "LBracket", "]": "RBracket",
         ";": "Semicolon", "'": "Quote", ",": "Comma", ".": "Period", "/": "Slash", "Ctrl": "LCtrl",
         "Shift": "LShift", "Alt": "LAlt", "Win": "LWin", "Right Ctrl": "RCtrl", "Rightshift": "RShift",
         "Right Alt": "RAlt", "BackSpace": "Backspace"}

slot_of = {}
for s in range(128):
    t, m, u = keymap[s * 3:s * 3 + 3]
    if t == 0x20 and m == 0 and u:
        slot_of[("u", u)] = s
    elif t == 0x20 and m and not u:
        slot_of[("m", m)] = s
    elif (t, m, u) == (0xA0, 0x01, 0x00):
        slot_of["fn"] = s

xs = [int(k[1]) + int(k[3]) / 2 for k in keys]
ys = [int(k[2]) + int(k[4]) / 2 for k in keys]
x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
rows, ui = [], []
for k in keys:
    vk, x, y, w, h, tip = int(k[0]), int(k[1]), int(k[2]), int(k[3]), int(k[4]), k[5]
    if tip in modbit:
        slot = slot_of[("m", modbit[tip])]
    elif tip == "Fn":
        slot = slot_of["fn"]
    else:
        slot = slot_of[("u", usage[tip])]
    name = canon.get(tip, tip)
    cx, cy = (x + w / 2 - x0) / (x1 - x0), (y + h / 2 - y0) / (y1 - y0)
    rows.append((name, slot, round(cx, 4), round(cy, 4), vk))
    ui.append({"name": name, "label": tip.replace("\\\\", "\\"), "x": x, "y": y, "w": w, "h": h})

rows.sort(key=lambda r: (round(r[3], 1), r[2]))
assert len({r[1] for r in rows}) == len(rows), "duplicate slot"
with open(os.path.join(ROOT, "evision_rgb", "layout.py"), "w", encoding="utf-8") as f:
    f.write('"""AK820 key layout. GENERATED by scripts/gen_layout.py — do not edit by hand.\n\n'
            "KEYS: name -> (led_slot, x, y) with x,y in 0..1 (key centre, from the official app's\n"
            "virtual keyboard). led_slot = column*8 + row of the firmware matrix (cmd 0x07).\n\"\"\"\n\n")
    f.write("KEYS = {\n")
    for name, slot, cx, cy, vk in rows:
        f.write(f"    {name!r}: ({slot}, {cx}, {cy}),\n")
    f.write("}\n\nSLOT_TO_KEY = {v[0]: k for k, v in KEYS.items()}\n")
import json
web = os.path.join(ROOT, "evision_rgb", "gui", "web")
os.makedirs(web, exist_ok=True)
with open(os.path.join(web, "layout.json"), "w", encoding="utf-8") as f:
    json.dump({"device": "ak820", "name": "AJAZZ AK820", "keys": ui,
               "decor": [{"type": "knob", "x": 543, "y": 15, "w": 30, "h": 30}]}, f, indent=1)
print(f"wrote {len(rows)} keys (+ gui/web/layout.json)")
